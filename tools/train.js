// Headless champion training (Node): evolves a population on each preset
// track until the elite genome can lap reliably, then writes the weights
// to src/tracks/champions.js (committed, embedded in the demo).
//
// Run: node tools/train.js
// Deterministic: fixed RNG seed per track.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { buildTrack } from '../src/sim/track.js';
import { PRESETS } from '../src/tracks/presets.js';
import { Simulation, SIM, stepCarWithBrain } from '../src/sim/simulation.js';
import { createCar } from '../src/sim/car.js';
import { makeRng } from '../src/sim/rng.js';

const POP = 100;
const SIGMA = 0.2;
const GENS = 120; // keep evolving and keep the fastest qualifying champion
const EVAL_TIME = 90; // s
const TARGET_LAPS = 3;
// Replayed in whatever browser engine the visitor uses: transcendental
// functions may differ by an ULP and diverge over thousands of steps, so
// only accept champions that also lap from slightly perturbed starts.
const PERTURBATIONS = [
  { dx: 0, dy: 0, dh: 0 },
  { dx: 2.5, dy: 0, dh: 0.02 },
  { dx: -2.5, dy: 0, dh: -0.02 },
  { dx: 0, dy: 2.5, dh: 0.015 },
  { dx: 0, dy: -2.5, dh: -0.015 },
];

function soloRun(track, genome, perturbation) {
  const car = createCar(track.startPose);
  car.x += perturbation.dx;
  car.y += perturbation.dy;
  car.heading += perturbation.dh;
  const steps = Math.ceil(EVAL_TIME / SIM.dt);
  for (let s = 0; s < steps; s++) {
    stepCarWithBrain(track, car, genome, SIM.dt);
    if (!car.alive) break;
  }
  return { crashed: !car.alive, progress: car.progressDist };
}

// A genome qualifies if it laps >= TARGET_LAPS without crashing from every
// perturbed start; its score is the worst-case distance covered.
function championScore(track, genome) {
  let worst = Infinity;
  for (const p of PERTURBATIONS) {
    const r = soloRun(track, genome, p);
    if (r.crashed || r.progress < TARGET_LAPS * track.lapLength) return -1;
    worst = Math.min(worst, r.progress);
  }
  return worst;
}

function trainOne(preset, seed) {
  const track = buildTrack(preset);
  const v = track.validate();
  if (!v.ok) throw new Error(`${preset.id}: invalid track (${v.reason} @ ${v.index})`);
  const sim = new Simulation({ track, popSize: POP, sigma: SIGMA, rng: makeRng(seed) });
  const maxSteps = Math.ceil(SIM.genTime / SIM.dt) + 2;

  let best = null;
  for (let gen = 1; gen <= GENS; gen++) {
    let steps = 0;
    while (!sim.step() && steps++ < maxSteps) {
      /* run the generation to its end */
    }
    const h = sim.history[sim.history.length - 1];
    if (gen % 20 === 0) {
      console.log(
        `${preset.id} gen ${gen}: best ${(h.best / track.lapLength).toFixed(2)} laps, mean ${Math.round(h.mean)}px`,
      );
    }
    // After evolve(), genomes[0] is the unmutated elite of the generation
    // that just ended.
    if (h.best >= 2 * track.lapLength) {
      const elite = sim.genomes[0];
      const score = championScore(track, elite);
      if (score > 0 && (!best || score > best.score)) {
        best = { gens: gen, score, weights: elite.map((w) => Number(w.toFixed(5))) };
      }
    }
  }
  if (!best) throw new Error(`${preset.id}: no champion after ${GENS} generations`);
  const lapsIn90s = (best.score / track.lapLength).toFixed(1);
  console.log(`${preset.id}: champion from generation ${best.gens}, ${lapsIn90s} laps in ${EVAL_TIME}s`);
  return { gens: best.gens, weights: best.weights };
}

const seeds = { parking: 1101, departementale: 2202, col: 3303 };
const champions = {};
for (const preset of PRESETS) {
  const t0 = Date.now();
  champions[preset.id] = trainOne(preset, seeds[preset.id]);
  console.log(`${preset.id}: done in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
}

const file = `// GENERATED by tools/train.js — do not edit by hand.
// Pre-trained "champion" networks, one per preset track (see README).
export const CHAMPIONS = ${JSON.stringify(champions, null, 2)};
`;
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'tracks', 'champions.js');
writeFileSync(out, file);
console.log(`wrote ${out}`);
